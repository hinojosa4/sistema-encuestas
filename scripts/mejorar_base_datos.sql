-- 4. Restricciones aditivas e idempotentes.
-- NOT VALID conserva los registros historicos; SI se exige en INSERT/UPDATE nuevos.
-- No se crean reglas que vacien ramas o rechacen automaticamente historicos.
DO $$
DECLARE
    tabla TEXT;
    campo TEXT;
    nombre TEXT;
    expresion TEXT;
BEGIN
    FOREACH tabla IN ARRAY ARRAY['encuesta_titulados', 'encuesta_empleadores'] LOOP
        nombre := tabla || '_importacion_fk';
        IF NOT EXISTS (SELECT 1 FROM pg_constraint
                       WHERE conrelid = format('public.%I', tabla)::regclass
                         AND conname = nombre) THEN
            EXECUTE format('ALTER TABLE public.%I ADD CONSTRAINT %I
                FOREIGN KEY (importacion_id) REFERENCES public.importaciones_encuestas(id)
                ON DELETE RESTRICT NOT VALID', tabla, nombre);
        END IF;

        FOREACH campo IN ARRAY ARRAY['raw_data', 'respuestas_originales',
                                     'codigos_ordinales', 'selecciones_multiples', 'calidad_datos'] LOOP
            nombre := tabla || '_' || campo || '_obj';
            IF NOT EXISTS (SELECT 1 FROM pg_constraint
                           WHERE conrelid = format('public.%I', tabla)::regclass
                             AND conname = nombre) THEN
                EXECUTE format('ALTER TABLE public.%I ADD CONSTRAINT %I
                    CHECK (%I IS NULL OR jsonb_typeof(%I) = ''object'') NOT VALID',
                    tabla, nombre, campo, campo);
            END IF;
        END LOOP;

        nombre := tabla || '_fila_positiva';
        IF NOT EXISTS (SELECT 1 FROM pg_constraint
                       WHERE conrelid = format('public.%I', tabla)::regclass
                         AND conname = nombre) THEN
            EXECUTE format('ALTER TABLE public.%I ADD CONSTRAINT %I
                CHECK (fila_origen IS NULL OR fila_origen >= 2) NOT VALID', tabla, nombre);
        END IF;
    END LOOP;

    FOREACH campo IN ARRAY ARRAY['anios_vida_profesional_normalizados', 'tiempo_desempleado_meses'] LOOP
        nombre := 'titulados_' || campo || '_valido';
        expresion := format('%I IS NULL OR (%I >= 0 AND %I < ''Infinity''::numeric)', campo, campo, campo);
        IF NOT EXISTS (SELECT 1 FROM pg_constraint
                       WHERE conrelid = 'public.encuesta_titulados'::regclass
                         AND conname = nombre) THEN
            EXECUTE format('ALTER TABLE public.encuesta_titulados
                ADD CONSTRAINT %I CHECK (%s) NOT VALID', nombre, expresion);
        END IF;
    END LOOP;
END $$;


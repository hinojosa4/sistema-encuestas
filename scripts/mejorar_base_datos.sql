-- 3. Procedencia de cada archivo. No guarda datos personales de las respuestas.
CREATE TABLE IF NOT EXISTS public.importaciones_encuestas (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    tipo_encuesta TEXT NOT NULL
        CHECK (tipo_encuesta IN ('encuesta_titulados', 'encuesta_empleadores')),
    archivo_nombre TEXT NOT NULL CHECK (btrim(archivo_nombre) <> ''),
    archivo_sha256 TEXT NOT NULL CHECK (archivo_sha256 ~ '^[a-f0-9]{64}$'),
    hoja_nombre TEXT,
    instrumento_origen TEXT,
    version_instrumento TEXT,
    zona_horaria_origen TEXT,
    filas_detectadas INTEGER NOT NULL CHECK (filas_detectadas >= 0),
    filas_importadas INTEGER NOT NULL DEFAULT 0
        CHECK (filas_importadas >= 0 AND filas_importadas <= filas_detectadas),
    estado TEXT NOT NULL DEFAULT 'pendiente'
        CHECK (estado IN ('pendiente', 'completada', 'fallida')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    finalizada_at TIMESTAMPTZ,
    CONSTRAINT importaciones_fecha_orden CHECK
        (finalizada_at IS NULL OR finalizada_at >= created_at)
);

-- Una misma huella puede tener intentos fallidos; solo se publica una carga completa
-- por tipo/archivo/hoja. No se impone unicidad a nombres, empresas o emails.
CREATE UNIQUE INDEX IF NOT EXISTS importaciones_archivo_completado_uidx
    ON public.importaciones_encuestas
       (tipo_encuesta, archivo_sha256, COALESCE(hoja_nombre, ''))
    WHERE estado = 'completada';


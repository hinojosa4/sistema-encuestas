-- Script SQL para la tabla encuesta_empleadores en Supabase
-- Ejecuta este script en el SQL Editor de tu panel de Supabase si necesitas crear o actualizar la tabla

CREATE TABLE IF NOT EXISTS public.encuesta_empleadores (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT TIMEZONE('utc'::TEXT, NOW()),
    
    -- 0. Datos Generales de la Empresa
    correo_electronico TEXT,
    nombre_empresa TEXT,
    tipo_organizacion TEXT, -- Público / Privado
    tamano_organizacion TEXT, -- Grande, Mediana, Pequeña, Micro
    rubro_sector TEXT,
    
    -- 1. Empleabilidad y Demanda
    ha_contratado_sistemas TEXT, -- SI / No
    probabilidad_incorporacion_futura TEXT,
    nivel_formacion_demandado TEXT,
    medio_convocatoria TEXT,
    cargos_desempenados TEXT,
    areas_emergentes_importantes TEXT,
    herramientas_tecnologicas_demandadas TEXT,
    habilidades_fundamentales TEXT,
    
    -- 2. Formación y Perfil Profesional (Escala Likert numérica 1 a 5)
    confianza_carrera_formadora NUMERIC,
    consistencia_titulo_competencias NUMERIC,
    consulta_regular_opinion NUMERIC,
    conocimiento_perfil_egreso NUMERIC,
    coherencia_perfil_desempeno NUMERIC,
    formacion_desempeno_destacado NUMERIC,
    incorporacion_necesidades_practicas NUMERIC,
    evidencia_competencias_laborales NUMERIC,
    valores_etica_responsabilidad NUMERIC,
    participacion_evaluacion_desempeno NUMERIC,
    
    -- 3. Relación de la Carrera con la Organización (Escala Likert numérica 1 a 5)
    vinculos_oportunidades_laborales NUMERIC,
    participacion_vinculacion_entorno NUMERIC,
    participacion_difusion_pasantias NUMERIC,
    participacion_intercambio_conocimiento NUMERIC,
    consulta_retroalimentacion_plan NUMERIC,
    consulta_pertinencia_formacion NUMERIC,
    busqueda_talento_umss NUMERIC,
    consulta_procesos_autoevaluacion NUMERIC,

    -- Respaldo crudo de la fila original por seguridad
    raw_data JSONB
);

-- Habilitar RLS (opcional si ya está público)
ALTER TABLE public.encuesta_empleadores ENABLE ROW LEVEL SECURITY;

-- Política para permitir lectura y escritura desde la aplicación (usando clave anon)
CREATE POLICY "Permitir lectura para todos" ON public.encuesta_empleadores
    FOR SELECT USING (true);

CREATE POLICY "Permitir insercion para anonimos" ON public.encuesta_empleadores
    FOR INSERT WITH CHECK (true);
